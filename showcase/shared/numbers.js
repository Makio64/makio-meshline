/** Values that must never be printed (wrong baseline). Kept only so a guard can catch them. */
export const BANNED = Object.freeze( ['267×', '6,780×', '−99.94%', '298×'] )

/**
 * Strict getter: throws on unknown ids or numbers that have no value yet.
 * @param {keyof typeof numbers} id
 */
export function num( id ) {
	const entry = numbers[id]
	if ( !entry ) throw new Error( `numbers: unknown id "${id}"` )
	if ( entry.value === null ) throw new Error( `numbers: "${id}" must be measured live (${entry.note})` )
	return entry
}

/** Throws if a string contains a banned figure. Use on any composed label in dev. */
export function assertPrintable( text ) {
	for ( const bad of BANNED ) {
		if ( String( text ).includes( bad ) ) throw new Error( `numbers: "${bad}" must never be printed` )
	}
	return text
}

export default numbers
