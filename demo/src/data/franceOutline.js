// Stylised France: the mainland border walked clockwise from Dunkerque, Corsica,
// and the four main rivers. Coordinates are hand-placed WGS84 degrees — accurate
// enough to read as France at a glance, far coarser than a real IGN dataset.
// Line simplification was invented for exactly this shape, so it makes the most
// honest default for the lab.
//
// Stored as whitespace-separated "lon lat" text so a coastline stays readable as
// a coastline instead of one array element per line.

const coordinates = source => {
	const values = source.trim().split( /[\s,]+/ ).map( Number )
	const points = []
	for ( let i = 0; i + 1 < values.length; i += 2 ) points.push( [values[i], values[i + 1]] )
	return points
}

